// 탭 ⑤ 안내 —— 자료가 어디서 왔고, 이 앱이 무엇을 못 하는지 밝힌다.
//
// ★ 이 앱의 원칙 —— 「모르는 것을 모른다고 말한다」.
//   분류가 없는 11.8% 를 억지로 채우지 않고, 학과명이 모집단위가 아니라는 것을
//   화면마다 적어 둔다. 합격 가능성은 한마디도 말하지 않는다.

import { h, b, comma } from '../lib/ui.js'
import {
  lead, card, row, cols, stat, note, warn, caution, tip, source, table, details, tag,
} from '../lib/widgets.js'
import { bars } from '../lib/chart.js'
import { meta, 통계, 계열나무 } from '../lib/data.js'
import { 지도meta } from '../lib/place.js'

function 자료화면() {
  const t = 통계()
  return h('div',
    lead('이 앱에 대하여',
      h('p', '전국 대학의 학과 이름을 모아 ', b('같은 갈래끼리 묶어 보는 도구'), '입니다. ',
        '진학 상담에서 「이름은 달라도 같은 학과」를 놓치지 않게 하려고 만들었습니다.')),

    card('담긴 자료',
      cols(4,
        stat('학과(학부)', `${comma(t.줄수)}개`),
        stat('대학·캠퍼스', `${comma(t.대학수)}곳`),
        stat('학과 이름 종류', `${comma(t.이름종류)}종`),
        stat('이름 뭉치', `${comma(t.열쇠종류)}종`)),
      h('h4', '큰 갈래별 학과 수'),
      bars(t.계열.map(([이름, 값]) => ({ 이름, 값 })), { 얇게: true }),
      h('h4', '지역별 학과 수'),
      bars(t.지역.slice(0, 17).map(([이름, 값]) => ({ 이름, 값 })), { 얇게: true })),

    card('어디서 온 자료인가',
      h('p', b('교육부 「대학알리미 키워드별 학과정보」'), ' (공공데이터포털)'),
      table(['항목', '내용'], [
        ['제공기관', '교육부 · 한국대학교육협의회 대학정보공시센터'],
        ['이용허락범위', h('span', b('공공저작물 제1유형'), ' — 출처만 밝히면 자유롭게 이용')],
        ['원본 행수', `${comma(meta.원본행수)}행 (대학원 포함)`],
        ['이 앱이 쓴 행', `${comma(meta.행수)}행 (학부만)`],
      ], { 정렬: ['left', 'left'] }),
      tip(b('이 앱을 공개해도 되는 까닭입니다. '),
        '입시 자료 가운데는 「공교육기관에서만 사용」처럼 조건이 붙은 것이 많은데, ',
        '이 자료는 공공저작물이라 출처만 밝히면 됩니다. ',
        '그래서 이 앱에는 ', b('입시 결과·전형 자료를 한 줄도 넣지 않았습니다'), '.')),

    card('지도는 어디서 왔나 (학과 위치 지도)',
      table(['항목', '내용'], [
        ['시·도 경계', 지도meta.경계출처],
        ['경계 조건', '「Free to share or remix」 — 출처(통계청)를 밝힙니다'],
        ['시·군·구 위치', '시청·군청·구청 부근의 위경도를 직접 적은 값 (사실이라 저작물이 아닙니다)'],
      ], { 정렬: ['left', 'left'] }),
      caution(b('점은 캠퍼스의 정확한 위치가 아닙니다. '),
        '그 학과가 있는 시·군·구의 대표 위치(시청·군청·구청 부근)에 찍었습니다. ', 지도meta.경계주의)),

    card('이 앱이 못 하는 것 — 정직하게 밝힙니다',
      h('ul',
        h('li', b('합격 가능성을 말하지 않습니다. '),
          '입결·경쟁률·등급 자료가 아예 들어 있지 않습니다.'),
        h('li', b('학과명은 「모집단위」가 아닙니다. '),
          '대학이 실제로 학생을 뽑는 단위는 「인문계열」·「자유전공학부」처럼 '
          + '여러 학과를 묶은 이름일 때가 많습니다. 지원 전에 모집요강을 꼭 확인하세요.'),
        h('li', b(`표준분류가 없는 학과가 ${comma(t.분류없는수)}개(${t.분류없는비율.toFixed(1)}%) 있습니다. `),
          '자유전공·광역모집이 대부분입니다. 억지로 채우지 않고 「분류 없음」으로 두었습니다.'),
        h('li', b('대학원은 뺐습니다. '), '고교 진학 상담용이라 학부만 담았습니다.'),
        h('li', b('공시 시점 기준입니다. '),
          '학과는 해마다 새로 생기고 없어집니다. 신설·변경·통합 표시를 함께 보여 주지만, '
          + '가장 정확한 것은 그 대학 홈페이지입니다.'),
        h('li', b('「이름이 비슷한 학과」는 어림입니다. '),
          '어간만 견주므로 뜻이 다른 학과가 섞일 수 있습니다. 표준분류 쪽이 더 믿을 만합니다.'))),

    card('개인정보',
      h('p', '이 앱은 ', b('이름·학번을 한 글자도 받지 않습니다'), '. ',
        '서버가 없고, 입력한 내용은 밖으로 나가지 않습니다. ',
        '브라우저를 닫으면 아무것도 남지 않습니다.')),

    source('학과 정보', meta.출처, meta.주의))
}

function 분류화면() {
  return h('div',
    lead('표준분류계열 전체 보기',
      h('p', '교육부가 학과마다 매긴 ', b('대 6 → 중 28 → 소 160'), ' 분류 전체입니다. ',
        '이 앱이 「같은 갈래」를 판단하는 근거입니다.')),
    ...계열나무.map((d) => card(`${d.이름} — 학과 ${d.수.toLocaleString('ko-KR')}개`,
      table(['중간 갈래', '학과 수', '작은 갈래'],
        d.자식.map((m) => [
          m.이름,
          m.수.toLocaleString('ko-KR'),
          h('div.row', ...m.자식.map((s) => tag(`${s.이름} ${s.수}`, 'brand'))),
        ]),
        { 정렬: ['left', 'right', 'left'], 좁게: true }))),
    source('학과 정보', meta.출처, meta.주의))
}

export default {
  id: 'annae',
  name: '안내',
  icon: '📖',
  screens: [
    { id: 'jaryo', name: '이 앱에 대하여', render: 자료화면 },
    { id: 'bunryu', name: '표준분류 전체', render: 분류화면 },
  ],
}
