// 탭 ② 학과 찾기 —— 이 앱의 핵심 화면.
//
// 학과 이름을 하나 넣으면 「같은 갈래인데 이름이 다른 학과」를 전부 보여 준다.
// 상담에서 「컴퓨터공학과에 가고 싶어요」라는 학생에게
// 「이름은 다르지만 같은 갈래인 학과가 이만큼 있다」를 보여 주는 것이 목적이다.
//
// ⚠ 근거를 **섞지 않는다.** 「분류가 같다」와 「이름이 비슷하다」를 따로 보여 주고,
//   둘 다 같은 것을 맨 위에 둔다. 어느 근거인지 모르면 학생이 잘못 믿는다.

import { h, b, comma, redraw, uniq } from '../lib/ui.js'
import {
  lead, card, panel, row, cols, stat, note, caution, tip, source,
  table, input, button, details, tag, empty,
} from '../lib/widgets.js'
import {
  meta, 학과찾기, 이웃학과, 소분류줄, 열쇠줄, 없음,
} from '../lib/data.js'
import { 지도주소 } from '../lib/place.js'

let 검색어 = ''
let 고른이름 = ''

/** 다른 탭에서 「이 학과 보기」로 넘어올 때 쓴다 */
export function 학과열기(이름) {
  검색어 = 이름
  고른이름 = 이름
  location.hash = '#chatgi/hakgwa'
  redraw()
}

const 지역줄 = (줄들) => {
  const m = new Map()
  for (const r of 줄들) m.set(r.대학.지역, (m.get(r.대학.지역) || 0) + 1)
  return [...m.entries()].sort((a, b) => b[1] - a[1])
}

function 검색카드() {
  const 결과 = 학과찾기(검색어)
  return card('학과 이름으로 찾기',
    row(
      input(검색어, (v) => { 검색어 = v; 고른이름 = '' },
        { 라벨: '학과 이름', 안내: '예: 컴퓨터공학과 · 간호 · 심리 · 자유전공', 다시그리기: true }),
      검색어 ? button('지우기', () => { 검색어 = ''; 고른이름 = ''; redraw() }, { 평평: true }) : null),
    !검색어
      ? h('p.dim', `전국 ${comma(meta.대학수)}개 대학의 학과 이름 `
        + `${comma(meta.행수)}개에서 찾습니다. 일부만 쳐도 됩니다.`)
      : (결과.length
        ? h('div',
          h('p.dim', `${결과.length}종${결과.length >= 60 ? ' 이상' : ''}을 찾았습니다. 하나를 고르세요.`),
          table(['학과 이름', '개설 대학', '표준분류(소)', ''],
            결과.map((x) => [
              x.이름,
              `${x.대학수}곳`,
              x.소 === 없음 ? h('span.dim', 없음) : x.소,
              button(고른이름 === x.이름 ? '보는 중' : '자세히',
                () => { 고른이름 = x.이름; redraw() },
                { 꺼짐: 고른이름 === x.이름, 평평: true }),
            ]),
            { 정렬: ['left', 'right', 'left', 'right'], 높이: '340px', 좁게: true }))
        : empty('그런 이름의 학과가 없습니다. 낱말 일부만 쳐 보세요.')))
}

function 자세히카드() {
  const 결과 = 학과찾기(고른이름)
  const 하나 = 결과.find((x) => x.이름 === 고른이름)
  if (!하나) return null
  const 이웃 = 이웃학과(하나.줄들[0])
  const 같은분류수 = 하나.소 === 없음 ? 0 : uniq(소분류줄(하나.소).map((r) => r.대학번호)).length
  const 지역 = 지역줄(하나.줄들)

  const 이름단추 = (n) => button(n, () => { 검색어 = n; 고른이름 = n; redraw() }, { 평평: true, 작게: true })

  return h('div',
    card(`${하나.이름}`,
      cols(4,
        stat('개설 대학', `${하나.대학수}곳`),
        stat('표준분류(대)', 하나.대 === 없음 ? '-' : 하나.대),
        stat('표준분류(중)', 하나.중 === 없음 ? '-' : 하나.중),
        stat('표준분류(소)', 하나.소 === 없음 ? '-' : 하나.소)),
      하나.소 === 없음
        ? caution(b('이 학과는 표준분류계열이 없습니다. '),
          '자유전공·광역모집처럼 여러 갈래를 아우르는 모집 단위가 대개 그렇습니다. ',
          '아래 「이름이 비슷한 학과」만 참고하세요.')
        : h('p.dim', `같은 소분류 「${하나.소}」로 묶인 학과가 전국 ${같은분류수}개 대학에 있습니다.`),
      지역.length
        ? h('div',
          h('h4', '어느 지역에 있나'),
          h('div.row', ...지역.map(([g, n]) => tag(`${g} ${n}`, 'brand')),
            button('📍 지도로 보기', () => { location.hash = 지도주소(하나.이름) }, { 주요: true })))
        : null),

    이웃.둘다.length
      ? card('🎯 거의 확실히 같은 학과',
        h('p.dim', '표준분류도 같고 이름도 비슷합니다. 두 근거가 모두 「같다」고 한 것입니다.'),
        h('div.row', ...이웃.둘다.map(이름단추)))
      : null,

    card('① 표준분류가 같은 학과',
      하나.소 === 없음
        ? empty('이 학과는 표준분류가 없어 이 방법으로는 묶이지 않습니다.')
        : h('div',
          h('p.dim', `교육부 대학알리미의 표준분류계열 「${하나.소}」에 함께 들어 있는 이름입니다. `
            + '우리가 지어낸 묶음이 아니라 원자료에 있는 분류입니다.'),
          이웃.분류기준.length
            ? h('div.row', ...이웃.분류기준.map(이름단추))
            : empty('같은 분류에 다른 이름이 없습니다.'))),

    card('② 이름이 비슷한 학과',
      h('p.dim', '괄호와 「학과·학부·전공」 같은 꼬리를 떼고 어간이 같은 것을 모았습니다.'),
      이웃.이름기준.length
        ? h('div.row', ...이웃.이름기준.map(이름단추))
        : empty('이름이 비슷한 다른 학과가 없습니다.'),
      caution(b('이 방법은 어림입니다. '),
        '「국제학부」와 「국제통상학부」처럼 어간만 같고 실제로는 다른 학과가 섞일 수 있습니다. ',
        '위 ①(표준분류)이 더 믿을 만합니다.')),

    card('개설 대학 목록',
      table(['대학', '지역', '학교종류', '주야', '상태'],
        하나.줄들
          .slice()
          .sort((a, b) => a.대학.지역.localeCompare(b.대학.지역, 'ko')
            || a.대학.표시.localeCompare(b.대학.표시, 'ko'))
          .map((r) => [r.대학.표시, r.대학.지역, r.대학.학교종류, r.주야,
            r.상태 === '기존' ? h('span.dim', '기존') : tag(r.상태, 'warn')]),
        { 정렬: ['left', 'left', 'left', 'left', 'left'], 높이: '360px', 좁게: true })),
  )
}

function 화면() {
  return h('div',
    lead('학과 찾기',
      h('p', '학과 이름을 넣으면 ', b('같은 갈래인데 이름이 다른 학과'), '를 찾아 줍니다. ',
        '「컴퓨터공학과」 하나만 알고 있어도 갈 수 있는 길이 얼마나 넓은지 보입니다.')),
    검색카드(),
    고른이름 ? 자세히카드() : null,
    note(b('⚠ 학과명은 입시의 「모집단위」와 다릅니다. '),
      '여기 나오는 것은 대학이 공시한 ', b('학과·전공 이름'), '입니다. ',
      '실제로 학생을 뽑는 단위는 「인문계열」·「자유전공학부」처럼 여러 학과를 묶은 이름일 때가 많습니다. ',
      '지원할 때는 반드시 그 대학의 모집요강을 확인하세요.'),
    source('학과 정보', meta.출처, meta.주의))
}

export default {
  id: 'chatgi',
  name: '학과 찾기',
  icon: '🔎',
  screens: [{ id: 'hakgwa', name: '학과 찾기', render: 화면 }],
}
