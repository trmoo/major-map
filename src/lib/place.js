// ── 어떤 학과를 지도에 올리나 ────────────────────────────────
/**
 * 세 가지 기준 — 섞지 않고 화면에서 고르게 한다.
 *   이름 : 이름이 똑같은 학과만
 *   열쇠 : 이름이 비슷한 학과(이름 열쇠가 같은 것). 어림이다.
 *   소   : 표준분류(소)가 같은 학과. 원자료의 분류다.
 */
export const 기준목록 = [
  { 값: '이름', 이름: '이 이름 그대로' },
  { 값: '열쇠', 이름: '이름이 비슷한 학과' },
  { 값: '소', 이름: '같은 표준분류(소)' },
]

/** 학과 이름의 표준분류(소). 같은 이름이 여러 분류에 걸치면 가장 많은 것. */
export function 이름의소분류(이름) {
  const m = new Map()
  for (const r of 모든줄) if (r.이름 === 이름) m.set(r.소, (m.get(r.소) || 0) + 1)
  let best = null
  for (const [k, n] of m) if (!best || n > best[1]) best = [k, n]
  return best ? best[0] : null
}

/**
 * 지도에 올릴 줄들.
 * ⚠ 표준분류가 없는 학과는 「같은 표준분류」로 묶지 않는다 —
 *   묶으면 자유전공과 광역모집이 통째로 한 학과가 된다(학과 찾기 화면과 같은 규칙).
 */
export function 지도줄(이름, 기준, 갈래들 = 기본학교갈래) {
  const 켬 = new Set(갈래들)
  const 통과 = (r) => 켬.has(학교갈래(r.대학.학교종류))
  if (!이름) return 모든줄.filter(통과)
  if (기준 === '열쇠') {
    const k = 이름열쇠(이름)
    return k ? 모든줄.filter((r) => r.열쇠 === k && 통과(r)) : []
  }
  if (기준 === '소') {
    const 소 = 이름의소분류(이름)
    if (!소 || 소 === 없음) return []
    return 모든줄.filter((r) => r.소 === 소 && 통과(r))
  }
  return 모든줄.filter((r) => r.이름 === 이름 && 통과(r))
}

/** 기준마다 대학이 몇 곳인가 — 알약 단추에 적어 「넓히면 이만큼 는다」를 보여 준다 */
export function 기준별대학수(이름, 갈래들 = 기본학교갈래) {
  const out = {}
  for (const g of 기준목록) out[g.값] = new Set(지도줄(이름, g.값, 갈래들).map((r) => r.대학번호)).size
  return out
}

// ── 점으로 묶기 ─────────────────────────────────────────────
/**
 * 줄들을 지도 점으로 묶는다.
 *   전국 : 광역시·특별시는 도시 하나를 점 하나로(구마다 찍으면 점이 겹쳐 안 보인다),
 *          도는 시·군마다.
 *   자세히 : 모든 시·군·구를 따로 (수도권 확대 상자가 쓴다).
 * 점 하나에는 **대학이 몇 곳인가**를 센다(한 대학의 주간·야간 두 줄은 한 곳).
 * @returns [{열쇠, 이름표, 시도, 시군구들, 좌표:[x,y], 대학: Map(대학번호 → 줄[])}]
 */
export function 점으로묶기(줄들, 수준 = '전국') {
  const m = new Map()
  for (const r of 줄들) {
    const 합침 = 수준 === '전국' && 광역시인가(r.시도)
    const k = 합침 ? r.시도 : `${r.시도} ${r.시군구}`
    if (!m.has(k)) {
      let 좌표
      if (합침) {
        const s = 시도경계.find((x) => x.이름 === r.시도)
        좌표 = s ? s.이름표 : [0, 0]
      } else {
        const ll = 자리좌표(r.시도, r.시군구)
        좌표 = ll ? 투영(ll[0], ll[1]) : null
      }
      m.set(k, {
        열쇠: k, 시도: r.시도, 이름표: 합침 ? r.시도 : r.시군구,
        시군구들: new Set(), 좌표, 대학: new Map(),
      })
    }
    const 점 = m.get(k)
    점.시군구들.add(r.시군구)
    if (!점.대학.has(r.대학번호)) 점.대학.set(r.대학번호, [])
    점.대학.get(r.대학번호).push(r)
  }
  return [...m.values()].filter((p) => p.좌표)
    .sort((a, b) => b.대학.size - a.대학.size || a.열쇠.localeCompare(b.열쇠, 'ko'))
}

/** 점 크기(px) — 넓이가 대학 수에 비례하도록 제곱근을 쓴다 */
export const 점반지름 = (n) => 4.5 + 3.2 * Math.sqrt(n)

/** 시·도별로 대학을 센다 (지도 아래 표가 쓴다) */
export function 시도별(줄들) {
  const m = new Map()
  for (const r of 줄들) {
    if (!m.has(r.시도)) m.set(r.시도, new Map())
    const u = m.get(r.시도)
    if (!u.has(r.대학번호)) u.set(r.대학번호, [])
    u.get(r.대학번호).push(r)
  }
  return [...m.entries()]
    .map(([시도, 대학]) => ({ 시도, 권역: 권역of(시도), 대학 }))
    .sort((a, b) => b.대학.size - a.대학.size || a.시도.localeCompare(b.시도, 'ko'))
}

/** 권역별 대학 수. 한 대학이 두 권역에 캠퍼스를 두면 두 곳 모두에서 센다. */
export function 권역별(줄들) {
  const m = new Map(권역이름.map((k) => [k, new Set()]))
  for (const r of 줄들) m.get(권역of(r.시도))?.add(`${r.대학번호}`)
  return 권역이름.map((k) => ({ 권역: k, 수: m.get(k).size }))
}

// ── 주소 ────────────────────────────────────────────────────
// 주소에는 기준을 영문 짧은 말로 적는다(한글은 %EC%.. 로 길게 늘어나 알려 주기 어렵다).
const 주소기준 = { 이름: '', 열쇠: 'key', 소: 'so' }

/**
 * 다른 화면에서 지도로 넘어오는 주소. 이 주소를 그대로 알려 주면 같은 지도가 열린다.
 * 예) #wichi/hakgwa?q=%EA%B0%84%ED%98%B8%ED%95%99%EA%B3%BC&by=so
 */
export function 지도주소(이름, 기준 = '이름') {
  if (!이름) return '#wichi/hakgwa'
  const by = 주소기준[기준] || ''
  return `#wichi/hakgwa?q=${encodeURIComponent(이름)}${by ? `&by=${by}` : ''}`
}

/** 지도주소() 의 반대. 모르는 기준은 「이름」으로 둔다. */
export function 지도주소읽기(hash) {
  const i = String(hash || '').indexOf('?')
  if (i < 0) return null
  const p = new URLSearchParams(String(hash).slice(i + 1))
  const q = (p.get('q') || '').trim()
  if (!q) return null
  const by = p.get('by') || ''
  const 기준 = Object.keys(주소기준).find((k) => 주소기준[k] && 주소기준[k] === by) || '이름'
  return { 이름: q, 기준 }
}
