// ── 투영 ────────────────────────────────────────────────────
// 우리나라처럼 좁은 땅은 「등장방형 + 위도 보정」이면 충분하다.
// 경도 1도의 길이는 위도가 올라갈수록 짧아지므로 cos(36.5°) 를 곱한다.
const 기준경도 = 124.5
const 기준위도 = 38.7
const 가로보정 = Math.cos((36.5 * Math.PI) / 180)
const 배 = 100                     // 위도 1도 = 100칸

/** [경도, 위도] → [x, y] (지도 칸) */
export function 투영(경도, 위도) {
  return [(경도 - 기준경도) * 가로보정 * 배, (기준위도 - 위도) * 배]
}

// 본토 지도가 차지하는 범위와, 그 안에 끼워 넣는 두 상자.
export const 전국틀 = (() => {
  const [x0, y0] = 투영(124.55, 38.66)
  const [x1, y1] = 투영(130.25, 33.08)
  return { x: x0, y: y0, 너비: x1 - x0, 높이: y1 - y0 }
})()

/** 수도권 확대 상자가 보여 주는 곳 (경도·위도) */
export const 수도권범위 = { 서: 126.45, 동: 127.72, 북: 38.0, 남: 36.96 }   // ⚠ 남쪽을 더 내리면 충북 음성군(36.94)이 들어온다
export const 수도권틀 = (() => {
  const [x0, y0] = 투영(수도권범위.서, 수도권범위.북)
  const [x1, y1] = 투영(수도권범위.동, 수도권범위.남)
  return { x: x0, y: y0, 너비: x1 - x0, 높이: y1 - y0 }
})()

// 울릉도·독도 — 본토에서 멀어 오른쪽 위 작은 상자로 옮겨 그린다.
const 동쪽섬 = { 서: 130.76, 동: 131.95, 북: 37.62, 남: 37.18 }
export const 섬상자 = (() => {
  const 너비 = 84
  const [a] = 투영(동쪽섬.서, 0)
  const [b2] = 투영(동쪽섬.동, 0)
  const 비율 = 너비 / (b2 - a)
  const 높이 = (동쪽섬.북 - 동쪽섬.남) * 배 * 비율
  return { x: 전국틀.x + 전국틀.너비 - 너비 - 8, y: 전국틀.y + 34, 너비, 높이, 비율 }
})()

/** 동쪽 섬의 [경도, 위도] → 섬 상자 안의 [x, y] */
export function 섬투영(경도, 위도) {
  const [x, y] = 투영(경도, 위도)
  const [x0, y0] = 투영(동쪽섬.서, 동쪽섬.북)
  return [섬상자.x + (x - x0) * 섬상자.비율, 섬상자.y + (y - y0) * 섬상자.비율]
}

