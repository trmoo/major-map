/**
 * 시·도마다 SVG 경로(d)를 만든다. 본토와 동쪽 섬(울릉도·독도)을 따로 돌려준다.
 * 경계 좌표는 경도·위도 × 1000 정수로 담겨 있다(make_map.py).
 */
export const 시도경계 = geo.sido.map((s) => {
  let 본토 = ''
  let 섬 = ''
  for (const 고리 of s.고리) {
    const 동쪽 = 고리[0] / 1000 > geo.동쪽섬경도
    const 점들 = []
    for (let i = 0; i < 고리.length; i += 2) {
      const [x, y] = 동쪽 ? 섬투영(고리[i] / 1000, 고리[i + 1] / 1000) : 투영(고리[i] / 1000, 고리[i + 1] / 1000)
      점들.push(`${x.toFixed(1)},${y.toFixed(1)}`)
    }
    const d = `M${점들.join('L')}Z`
    if (동쪽) 섬 += d
    else 본토 += d
  }
  const [lx, ly] = 투영(s.이름표[0], s.이름표[1])
  return { 이름: s.이름, 정식: s.정식, 권역: 권역of(s.이름), 광역시: 광역시인가(s.이름), 본토, 섬, 이름표: [lx, ly] }
})

