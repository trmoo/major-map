// 학과 위치 지도 — 자리·묶기·주소 규칙을 지킨다.
// ⚠ 시험은 탭 파일(DOM)을 부르지 않는다. place.js 는 DOM 을 만들지 않아 그대로 부른다.

import { 묶음, 확인, 참이어야 } from './harness.mjs'
import { 모든줄, 모든대학, 없음 } from '../src/lib/data.js'
import {
  투영, 전국틀, 수도권틀, 수도권범위, 시도경계, 자리좌표,
  학교갈래, 기본학교갈래, 지도줄, 기준별대학수, 이름의소분류, 점으로묶기,
  시도별, 권역별, 지도주소, 지도주소읽기,
} from '../src/lib/place.js'

const 대학 = (이름, 구분 = '본교') => 모든대학.find((u) => u.학교명 === 이름 && u.구분 === 구분)

묶음('모든 학과에 자리가 있다')
// ⚠ 새 자료를 받으면 없는 시·군·구가 생길 수 있다. make_map.py 의 자리표에 더할 것.
참이어야('모든 줄에 시·도와 시·군·구가 있다', 모든줄.every((r) => r.시도 && r.시군구))
참이어야('모든 줄의 자리에 좌표가 있다', 모든줄.every((r) => 자리좌표(r.시도, r.시군구)))
확인('「전남광주」는 남지 않았다', 모든줄.filter((r) => r.시도 === '전남광주').length, 0)
참이어야('광주는 구만, 전남에는 구가 없다',
  모든줄.every((r) => (r.시도 === '광주') === (r.시도 === '광주' && r.시군구.endsWith('구')))
  && 모든줄.filter((r) => r.시도 === '전남').every((r) => !r.시군구.endsWith('구')))

묶음('자리는 학과마다 — 캠퍼스가 여럿인 대학')
// ★ 성균관대 본교 학과의 절반쯤은 수원(자연과학캠퍼스)에 있다. 본부 지역으로 찍으면 틀린다.
const 성대 = 대학('성균관대학교')
const 성대곳 = new Set(모든줄.filter((r) => r.대학번호 === 성대.번호).map((r) => `${r.시도} ${r.시군구}`))
참이어야('성균관대 본교는 종로구와 수원시 두 곳', 성대곳.has('서울 종로구') && 성대곳.has('경기 수원시'))
// ⚠ 예전에는 대학표의 첫 줄 값을 써서 연세대가 「서울 연수구」로 나왔다.
확인('연세대 본교의 대표 소재지', 대학('연세대학교').소재지, '서대문구')
확인('유원대의 대표 소재지는 본부 지역(충북) 안', 대학('유원대학교').소재지, '영동군')
참이어야('대표 소재지는 그 대학 학과가 실제로 있는 곳',
  모든대학.every((u) => 모든줄.some((r) => r.대학번호 === u.번호 && r.시군구 === u.소재지)))

묶음('지도 틀')
확인('시·도 경계 17곳', 시도경계.length, 17)
참이어야('모든 시·도에 본토 경계가 있다', 시도경계.every((s) => s.본토.startsWith('M')))
참이어야('울릉도·독도는 경북에만 있다',
  시도경계.filter((s) => s.섬).map((s) => s.이름).join() === '경북')
참이어야('모든 자리가 전국 틀 안', 모든줄.every((r) => {
  const ll = 자리좌표(r.시도, r.시군구)
  const [x, y] = 투영(ll[0], ll[1])
  return x > 전국틀.x && x < 전국틀.x + 전국틀.너비 && y > 전국틀.y && y < 전국틀.y + 전국틀.높이
}))
// ★ 전국 지도는 수도권 점을 빼고 확대 지도에만 찍는다. 그러려면 수도권 점이 모두
//   확대 상자 안에 있고, 수도권 아닌 점은 하나도 상자 안에 없어야 한다.
const 수도권 = new Set(['서울', '인천', '경기'])
const 상자안 = ([경, 위]) => 경 > 수도권범위.서 && 경 < 수도권범위.동 && 위 > 수도권범위.남 && 위 < 수도권범위.북
참이어야('수도권 점은 모두 확대 상자 안',
  모든줄.filter((r) => 수도권.has(r.시도)).every((r) => 상자안(자리좌표(r.시도, r.시군구))))
참이어야('수도권 아닌 점은 확대 상자 밖',
  모든줄.filter((r) => !수도권.has(r.시도)).every((r) => !상자안(자리좌표(r.시도, r.시군구))))
참이어야('확대 상자는 전국 틀 안', 수도권틀.x > 전국틀.x && 수도권틀.y > 전국틀.y)

묶음('학교 종류')
확인('사이버대학은 원격', 학교갈래('사이버대학(대학)'), '원격')
확인('방송통신대학은 원격', 학교갈래('방송통신대학'), '원격')
확인('교육대학은 4년제', 학교갈래('교육대학'), '4년제')
참이어야('원격대학은 기본으로 빠진다', !기본학교갈래.includes('원격')
  && 지도줄('', '이름').every((r) => 학교갈래(r.대학.학교종류) !== '원격'))
참이어야('원격대학을 켜면 들어온다',
  지도줄('', '이름', ['원격']).length > 0)

묶음('기준 — 섞지 않는다')
const 수 = 기준별대학수('컴퓨터공학과')
참이어야('이 이름 그대로 ≤ 같은 표준분류', 수.이름 > 0 && 수.이름 <= 수.소)
참이어야('이름 그대로는 모두 같은 이름', 지도줄('컴퓨터공학과', '이름').every((r) => r.이름 === '컴퓨터공학과'))
확인('컴퓨터공학과의 표준분류(소)', 이름의소분류('컴퓨터공학과'), '전산학・컴퓨터공학')
참이어야('같은 표준분류는 모두 같은 소분류',
  지도줄('컴퓨터공학과', '소').every((r) => r.소 === '전산학・컴퓨터공학'))
// ⚠ 분류가 없는 학과를 분류로 묶으면 자유전공과 광역모집이 통째로 한 학과가 된다.
const 분류없는이름 = 모든줄.find((r) => r.소 === 없음 && 이름의소분류(r.이름) === 없음).이름
확인(`분류 없는 학과(${분류없는이름})는 표준분류로 묶지 않는다`, 지도줄(분류없는이름, '소').length, 0)
확인('없는 학과는 빈 지도', 지도줄('없는학과이름', '이름').length, 0)

묶음('점으로 묶기')
const 전국 = 점으로묶기(지도줄('', '이름'), '전국')
const 자세히 = 점으로묶기(지도줄('', '이름'), '자세히')
확인('전국 지도에서 서울은 점 하나', 전국.filter((p) => p.시도 === '서울').length, 1)
참이어야('자세히 보면 서울은 구마다', 자세히.filter((p) => p.시도 === '서울').length >= 15)
참이어야('도는 전국 지도에서도 시·군마다', 전국.filter((p) => p.시도 === '경기').length >= 20)
참이어야('점은 대학 수가 많은 차례', 전국.every((p, i) => i === 0 || 전국[i - 1].대학.size >= p.대학.size))
// 한 대학의 주간·야간 두 줄은 한 곳으로 센다
const 합 = 자세히.reduce((a, p) => a + p.대학.size, 0)
const 짝 = new Set(지도줄('', '이름').map((r) => `${r.대학번호}|${r.시도} ${r.시군구}`)).size
확인('점마다 센 대학 수의 합 = (대학, 자리) 짝의 수', 합, 짝)
const 표 = 시도별(지도줄('간호학과', '이름'))
참이어야('시·도별 목록은 많은 차례', 표.every((x, i) => i === 0 || 표[i - 1].대학.size >= x.대학.size))
확인('권역은 여섯', 권역별(지도줄('간호학과', '이름')).length, 6)

묶음('주소')
// ★ 주소를 그대로 알려 주면 같은 지도가 열려야 한다.
for (const 기준 of ['이름', '열쇠', '소']) {
  확인(`주소 되읽기 — ${기준}`, 지도주소읽기(지도주소('간호학과', 기준)), { 이름: '간호학과', 기준 })
}
확인('기준 없는 주소는 짧다', 지도주소('간호학과'), `#wichi/hakgwa?q=${encodeURIComponent('간호학과')}`)
확인('by=so 는 표준분류', 지도주소읽기('#wichi/hakgwa?q=a&by=so').기준, '소')
확인('모르는 기준은 이름', 지도주소읽기('#wichi/hakgwa?q=a&by=zz').기준, '이름')
확인('학과가 없으면 null', 지도주소읽기('#wichi/hakgwa'), null)
확인('학과 없이 만든 주소', 지도주소(''), '#wichi/hakgwa')
확인('인코딩 안 된 한글도 읽는다', 지도주소읽기('#wichi/hakgwa?q=간호학과&by=key'), { 이름: '간호학과', 기준: '열쇠' })
