// 자료와 묶기 규칙을 지킨다.
// ⚠ 시험은 탭 파일(DOM)을 부르지 않는다. 화면 문법은 `npm run check:syntax` 가 본다.

import { 묶음, 확인, 참이어야 } from './harness.mjs'
import {
  meta, 모든줄, 모든대학, 없음, 이름열쇠, 계열나무, 통계,
  학과찾기, 대학찾기, 이웃학과, 소분류줄, 열쇠줄, 대학줄, 이름뭉치,
} from '../src/lib/data.js'

// ── 자료가 통째로 바뀌지 않았는가 ───────────────────────────
묶음('담긴 자료')
// ★ 교육부 「대학알리미 키워드별 학과정보」에서 학부만 추린 값이다.
//   자료를 새로 받아 npm run data 를 돌리면 이 숫자들이 바뀐다. 그때 함께 고칠 것.
확인('학부 학과 행수', meta.행수, 16221)
확인('원본은 대학원까지', meta.원본행수, 29475)
확인('대학·캠퍼스 수', meta.대학수, 408)
확인('줄과 meta 가 맞는다', 모든줄.length, meta.행수)
확인('대학과 meta 가 맞는다', 모든대학.length, meta.대학수)
참이어야('출처가 적혀 있다', meta.출처.includes('대학알리미'))
참이어야('이용허락이 적혀 있다', meta.이용허락.includes('공공저작물'))

묶음('대학원은 들어오지 않았다')
// ⚠ 고교 진학 상담용이라 학부만 담는다. 대학원이 섞이면 「학과 수」가 통째로 틀어진다.
참이어야('학교종류에 대학원이 없다',
  모든대학.every((u) => !u.학교종류.includes('대학원')))
확인('원본에서 걸러낸 행 수', meta.원본행수 - meta.행수, 13254)

묶음('표준분류계열 세 단계')
확인('큰 갈래 6종', 계열나무.length, 6)
확인('중간 갈래 28종',
  new Set(계열나무.flatMap((d) => d.자식.map((m) => m.이름))).size, 28)
확인('작은 갈래 160종',
  new Set(계열나무.flatMap((d) => d.자식.flatMap((m) => m.자식.map((s) => s.이름)))).size, 160)
확인('나무의 합이 전체와 같다',
  계열나무.reduce((a, d) => a + d.수, 0), meta.행수)
참이어야('큰 갈래는 인문사회계열이 가장 많다', 계열나무[0].이름 === '인문사회계열')

묶음('분류 없음을 지우지 않는다')
// ★ 자율전공·광역모집이라 요즘 입시에서 오히려 중요한 덩어리다.
//   억지로 채우지 않고 「모른다」고 남긴다.
const 통 = 통계()
확인('분류 없는 학과 수', 통.분류없는수, 1918)
참이어야('11~12% 사이다', 통.분류없는비율 > 11 && 통.분류없는비율 < 12)
참이어야('「분류 없음」이 갈래 목록에 들어 있다',
  계열나무.some((d) => d.자식.some((m) => m.자식.some((s) => s.이름 === 없음))))

// ── 이름 열쇠 ───────────────────────────────────────────────
묶음('이름 열쇠 — 꼬리는 덩어리로만 뗀다')
// ⚠⚠ 「학」·「과」 한 글자를 떼면 「컴퓨터공학」이 「컴퓨터공」처럼 이상해지고,
//    무엇보다 **떼는 자리에 따라 뭉치가 달라진다**. 덩어리로만 뗄 것.
확인('학과와 학부가 같은 열쇠', 이름열쇠('컴퓨터공학과'), 이름열쇠('컴퓨터공학부'))
확인('전공도 같은 열쇠', 이름열쇠('간호학과'), 이름열쇠('간호전공'))
확인('괄호는 버린다', 이름열쇠('간호학과(야간)'), 이름열쇠('간호학과'))
확인('가운뎃점·띄어쓰기도 버린다', 이름열쇠('AI · 소프트웨어학과'), 이름열쇠('AI소프트웨어학과'))
확인('두 겹으로 붙은 이름', 이름열쇠('간호학부(간호학전공)'), 이름열쇠('간호학과'))
참이어야('빈 값도 죽지 않는다', 이름열쇠(undefined) === '' && 이름열쇠(null) === '')
// ⚠ 뜻이 다른 것까지 묶으면 안 된다.
참이어야('국어교육과와 국어국문학과는 다른 열쇠',
  이름열쇠('국어교육과') !== 이름열쇠('국어국문학과'))
참이어야('기계공학과와 기계과는 다른 열쇠',
  이름열쇠('기계공학과') !== 이름열쇠('기계과'))

// ── 찾기 ────────────────────────────────────────────────────
묶음('학과 찾기')
const 간호 = 학과찾기('간호학과')
참이어야('결과가 있다', 간호.length > 0)
확인('딱 맞는 이름이 맨 앞', 간호[0].이름, '간호학과')
참이어야('간호학과는 100곳 넘게 있다', 간호[0].대학수 > 100)
확인('소분류는 간호학', 간호[0].소, '간호학')
확인('빈 말은 빈 결과', 학과찾기('').length, 0)
확인('없는 이름', 학과찾기('없는학과이름입니다').length, 0)
참이어야('일부만 쳐도 찾는다', 학과찾기('간호').length > 0)

묶음('대학 찾기')
참이어야('가천대가 있다', 대학찾기('가천').length > 0)
확인('빈 말은 빈 결과', 대학찾기('').length, 0)
참이어야('찾은 대학은 학과가 있다',
  대학찾기('가천').every((u) => 대학줄(u.번호).length > 0))

// ── 이웃 학과 ───────────────────────────────────────────────
묶음('이웃 학과 — 두 근거를 섞지 않는다')
// ★ 「분류가 같다」와 「이름이 비슷하다」는 다른 근거다. 섞으면 무엇을 믿는지 알 수 없다.
const 줄 = 간호[0].줄들[0]
const 이웃 = 이웃학과(줄)
참이어야('분류 기준 결과가 있다', 이웃.분류기준.length > 0)
참이어야('이름 기준 결과가 있다', 이웃.이름기준.length > 0)
참이어야('자기 자신은 빠진다',
  !이웃.분류기준.includes('간호학과') && !이웃.이름기준.includes('간호학과'))
참이어야('「둘 다」는 두 목록 모두에 있는 것만',
  이웃.둘다.every((n) => 이웃.분류기준.includes(n) && 이웃.이름기준.includes(n)))

묶음('분류가 없으면 분류 기준으로 묶지 않는다')
// ⚠ 「분류 없음」끼리 묶으면 자유전공과 광역모집이 통째로 한 학과가 된다. 그러면 안 된다.
const 없는줄 = 모든줄.find((r) => r.소 === 없음)
참이어야('분류 없는 학과가 있다', !!없는줄)
확인('분류 기준 이웃은 비어 있다', 이웃학과(없는줄).분류기준.length, 0)

// ── 이름 뭉치 ───────────────────────────────────────────────
묶음('이름 뭉치')
const 뭉치 = 이름뭉치(2)
참이어야('뭉치가 있다', 뭉치.length > 0)
참이어야('모든 뭉치는 이름이 둘 이상', 뭉치.every((x) => x.이름들.length >= 2))
참이어야('모든 뭉치는 대학이 둘 이상', 뭉치.every((x) => x.대학수 >= 2))
참이어야('이름 많은 순으로 정렬', 뭉치[0].이름들.length >= 뭉치[뭉치.length - 1].이름들.length)
참이어야('뭉치 안의 이름은 중복이 없다',
  뭉치.every((x) => new Set(x.이름들).size === x.이름들.length))

// ── 짜임새 ──────────────────────────────────────────────────
묶음('줄과 대학이 제대로 이어졌는가')
참이어야('모든 줄에 대학이 붙어 있다', 모든줄.every((r) => !!r.대학))
참이어야('모든 줄에 이름이 있다', 모든줄.every((r) => typeof r.이름 === 'string' && r.이름.length > 0))
참이어야('모든 줄에 세 갈래가 있다',
  모든줄.every((r) => !!r.대 && !!r.중 && !!r.소))
확인('소분류로 모으면 전체와 같다',
  [...new Set(모든줄.map((r) => r.소))].reduce((a, s) => a + 소분류줄(s).length, 0), meta.행수)
확인('열쇠로 모으면 전체와 같다',
  [...new Set(모든줄.map((r) => r.열쇠))].reduce((a, k) => a + 열쇠줄(k).length, 0), meta.행수)
확인('대학으로 모으면 전체와 같다',
  모든대학.reduce((a, u) => a + 대학줄(u.번호).length, 0), meta.행수)

묶음('통계')
확인('줄 수', 통.줄수, meta.행수)
확인('대학 수', 통.대학수, meta.대학수)
참이어야('지역이 여럿이다', 통.지역.length >= 15)
참이어야('학교종류가 여럿이다', 통.종류.length >= 5)
참이어야('계열 합이 전체와 같다', 통.계열.reduce((a, x) => a + x[1], 0) === meta.행수)

묶음('개인정보가 들어올 자리가 없다')
// ⚠ 이 앱은 공개 배포한다. 자료에 사람 이름이 섞이면 안 된다.
참이어야('대학 항목은 여섯 칸뿐',
  모든대학.every((u) => Object.keys(u).length === 8))   // 번호·표시 포함
참이어야('meta 에 개인정보 낱말이 없다',
  !JSON.stringify(meta).match(/이름표|학번|생년월일|주민/))
