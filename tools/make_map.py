def 넓이(ring):
    s = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        s += x1 * y2 - x2 * y1
    return abs(s) / 2


def 선거리(p, a, b):
    (x, y), (x1, y1), (x2, y2) = p, a, b
    dx, dy = x2 - x1, y2 - y1
    if dx == 0 and dy == 0:
        return math.hypot(x - x1, y - y1)
    t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - (x1 + t * dx), y - (y1 + t * dy))


def dp(pts, eps):
    """더글러스-포이커. 되부름 대신 쌓기로 돈다(긴 해안선에서 깊이 제한에 걸리지 않게)."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        best, k = 0.0, -1
        for m in range(i + 1, j):
            d = 선거리(pts[m], pts[i], pts[j])
            if d > best:
                best, k = d, m
        if best > eps:
            keep[k] = True
            stack += [(i, k), (k, j)]
    return [p for p, f in zip(pts, keep) if f]


def 고리줄이기(ring):
    pts = [tuple(p) for p in ring]
    if pts[0] == pts[-1]:
        pts = pts[:-1]
    # 닫힌 고리는 가장 먼 두 점으로 나눠 줄여야 모양이 무너지지 않는다.
    far = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
    a = dp(pts[:far + 1], 단순화)
    b = dp(pts[far:] + [pts[0]], 단순화)
    out = a[:-1] + b[:-1]
    return out if len(out) >= 4 else None


def 안에있나(x, y, ring):
    inside = False
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            inside = not inside
    return inside


def 경계거리(x, y, ring):
    return min(선거리((x, y), ring[i], ring[(i + 1) % len(ring)]) for i in range(len(ring)))


